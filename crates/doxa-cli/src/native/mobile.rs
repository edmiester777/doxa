//! The generated Xcode and Gradle projects under `gen/`, made by Tauri's `init` and kept in step
//! with the config, plus what local mode needs from them.

use std::ffi::OsString;
use std::path::Path;

use doxa_build::native::{NativeConfig, Server};
use doxa_build::Output;
use doxa_role::Target;
use sha2::{Digest, Sha256};

use super::{tauri, write_if_changed, Error};

/// The platform's directory under `gen/`, and its Tauri subcommand.
fn platform(target: Target) -> (&'static str, &'static str) {
    match target {
        Target::Ios => ("gen/apple", "ios"),
        _ => ("gen/android", "android"),
    }
}

/// What a generated project bakes in, patches included; a change means making it again.
fn stamp(dir: &Path, cfg: &NativeConfig, name: &str) -> String {
    let exe = std::env::current_exe().unwrap_or_default();
    let fragment = std::fs::read_to_string(dir.join(FRAGMENT)).unwrap_or_default();
    let parts = [
        cfg.identifier.as_str(),
        cfg.name.as_deref().unwrap_or(name),
        &tauri::version(),
        &exe.to_string_lossy(),
        &format!("{:?}", cfg.server),
        &fragment,
    ];
    hex::encode(Sha256::digest(parts.join("\n")))
}

/// Makes `gen/<platform>` if it's missing or stale; `true` when it did, so the icons go in again.
pub fn project(
    dir: &Path,
    cfg: &NativeConfig,
    name: &str,
    target: Target,
    out: &Output,
) -> Result<bool, Error> {
    let (gen, cmd) = platform(target);
    let stamp_path = dir.join(format!("gen/doxa/{cmd}.stamp"));
    let want = stamp(dir, cfg, name);
    let fresh = dir.join(gen).is_dir()
        && std::fs::read_to_string(&stamp_path).is_ok_and(|s| s.trim() == want);
    if fresh {
        return Ok(false);
    }
    if dir.join(gen).exists() {
        out.note(format!(
            "{gen} is from another config or doxa; making it again"
        ));
        std::fs::remove_dir_all(dir.join(gen))?;
    }
    let args: Vec<OsString> = [cmd, "init", "--ci", "--skip-targets-install"]
        .into_iter()
        .map(Into::into)
        .collect();
    tauri::run(dir, &args, &[], out)?;
    if target == Target::Android {
        android(dir, cfg)?;
    }
    write_if_changed(&stamp_path, &want)?;
    Ok(true)
}

/// Host C flags for an iOS build. Tauri's Xcode script points build scripts' C at the macOS SDK
/// only on an x86_64 Mac; on Apple Silicon they'd compile against the iOS one.
fn ios_host_flags() -> Vec<(&'static str, String)> {
    if !cfg!(all(target_os = "macos", target_arch = "aarch64")) {
        return Vec::new();
    }
    let sdk = std::process::Command::new("xcrun")
        .args(["--sdk", "macosx", "--show-sdk-path"])
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_owned())
        .filter(|s| !s.is_empty());
    match sdk {
        Some(sdk) => {
            let flags = format!("-isysroot {sdk}");
            vec![
                ("CFLAGS_aarch64_apple_darwin", flags.clone()),
                ("CXXFLAGS_aarch64_apple_darwin", flags),
            ]
        }
        None => Vec::new(),
    }
}

const CARGO_CONFIG: &str = ".cargo/config.toml";
const CARGO_MARK: &str = "# Generated by doxa for native builds; safe to delete.";

/// Writes `.cargo/config.toml` with the `[env]` a mobile build's cargo needs: `DOXA_DIST` for
/// the api crate's `dist!()` in local mode, and iOS's host C flags. Xcode and Gradle run cargo
/// without doxa's environment; cargo finds this from the crate's dir.
pub fn cargo_config(dir: &Path, target: Target, dist: Option<&Path>) -> Result<(), Error> {
    let mut env: Vec<(&str, String)> = Vec::new();
    if let Some(d) = dist {
        env.push(("DOXA_DIST", d.to_string_lossy().into_owned()));
    }
    if target == Target::Ios {
        env.extend(ios_host_flags());
    }
    write_cargo_config(dir, &env)
}

fn write_cargo_config(dir: &Path, env: &[(&str, String)]) -> Result<(), Error> {
    let path = dir.join(CARGO_CONFIG);
    if let Ok(text) = std::fs::read_to_string(&path) {
        if !text.starts_with(CARGO_MARK) {
            return Err(format!(
                "{} exists and isn't doxa's; a mobile build writes the `[env]` Xcode's and Gradle's \
                 cargo needs there\n  fix: move its settings to the workspace's .cargo/config.toml",
                path.display()
            )
            .into());
        }
    }
    if env.is_empty() {
        let _ = std::fs::remove_file(&path);
        return Ok(());
    }
    let mut text = format!("{CARGO_MARK}\n[env]\n");
    for (k, v) in env {
        text.push_str(&format!(
            "{k} = {}\n",
            toml_edit::value(v.as_str()).to_string().trim()
        ));
    }
    write_if_changed(&path, &text)?;
    Ok(())
}

const MANIFEST: &str = "gen/android/app/src/main/AndroidManifest.xml";
const NETWORK_CONFIG: &str = "gen/android/app/src/main/res/xml/network_security_config.xml";
const FRAGMENT: &str = "native/AndroidManifest.xml";
/// Release builds block cleartext; the local server is the one exception.
const CLEARTEXT_LOCAL: &str = r#"<?xml version="1.0" encoding="utf-8"?>
<network-security-config>
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="false">127.0.0.1</domain>
    </domain-config>
</network-security-config>
"#;

/// Applies local mode's network config and `native/AndroidManifest.xml` to the fresh project.
fn android(dir: &Path, cfg: &NativeConfig) -> Result<(), Error> {
    let manifest = dir.join(MANIFEST);
    let mut text = std::fs::read_to_string(&manifest)?;
    if cfg.server == Server::Local {
        write_if_changed(&dir.join(NETWORK_CONFIG), CLEARTEXT_LOCAL)?;
        text = with_network_config(&text);
    }
    if let Ok(fragment) = std::fs::read_to_string(dir.join(FRAGMENT)) {
        text = merged(&text, &fragment)?;
    }
    write_if_changed(&manifest, &text)?;
    Ok(())
}

fn with_network_config(manifest: &str) -> String {
    if manifest.contains("android:networkSecurityConfig") {
        return manifest.to_owned();
    }
    manifest.replacen(
        "<application",
        "<application\n        android:networkSecurityConfig=\"@xml/network_security_config\"",
        1,
    )
}

/// `fragment`'s `<application>` children go into the manifest's `<application>`; the rest of
/// what's inside its `<manifest>` goes into the manifest's.
fn merged(manifest: &str, fragment: &str) -> Result<String, Error> {
    let inner = |s: &str, tag: &str| -> Option<(usize, usize)> {
        let open = s.find(&format!("<{tag}"))?;
        let body = open + s[open..].find('>')? + 1;
        let close = s.rfind(&format!("</{tag}>"))?;
        (body <= close).then_some((body, close))
    };
    let (fb, fe) = inner(fragment, "manifest")
        .ok_or_else(|| format!("{FRAGMENT}: no <manifest>…</manifest>"))?;
    let body = &fragment[fb..fe];
    let (app, rest) = match inner(body, "application") {
        Some((ab, ae)) => {
            let open = body[..ab].rfind("<application").unwrap_or(ab);
            let close = ae + "</application>".len();
            (
                body[ab..ae].trim().to_owned(),
                format!("{}{}", &body[..open], &body[close..]),
            )
        }
        None => (String::new(), body.to_owned()),
    };
    let mut out = manifest.to_owned();
    if !app.is_empty() {
        let at = out
            .rfind("</application>")
            .ok_or("the generated AndroidManifest.xml has no </application>")?;
        out.insert_str(at, &format!("    {app}\n    "));
    }
    let rest = rest.trim();
    if !rest.is_empty() {
        let at = out
            .find("<application")
            .ok_or("the generated AndroidManifest.xml has no <application>")?;
        out.insert_str(at, &format!("{rest}\n\n    "));
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    const GENERATED: &str = "<manifest xmlns:android=\"x\">\n    <uses-permission android:name=\"android.permission.INTERNET\" />\n    <application\n        android:label=\"a\">\n        <activity android:name=\".MainActivity\" />\n    </application>\n</manifest>\n";

    #[test]
    fn the_fragment_s_application_children_and_permissions_land_in_their_places() {
        let fragment = "<manifest xmlns:android=\"x\">\n  <uses-permission android:name=\"android.permission.CAMERA\" />\n  <application>\n    <meta-data android:name=\"k\" android:value=\"v\" />\n  </application>\n</manifest>";
        let out = merged(GENERATED, fragment).unwrap();
        let camera = out.find("CAMERA").unwrap();
        let app = out.find("<application").unwrap();
        let meta = out.find("<meta-data").unwrap();
        let app_end = out.find("</application>").unwrap();
        assert!(camera < app && app < meta && meta < app_end, "{out}");
        assert!(merged(GENERATED, "<nope/>").is_err());
    }

    #[test]
    fn local_mode_allows_cleartext_to_its_server_once() {
        let once = with_network_config(GENERATED);
        assert!(once.contains("android:networkSecurityConfig=\"@xml/network_security_config\""));
        assert_eq!(with_network_config(&once), once);
        assert!(CLEARTEXT_LOCAL.contains("<domain includeSubdomains=\"false\">127.0.0.1</domain>"));
    }

    #[test]
    fn the_cargo_config_is_doxa_s_or_left_alone() {
        let dir = tempfile::tempdir().unwrap();
        cargo_config(
            dir.path(),
            Target::Android,
            Some(Path::new("/t/dist-android")),
        )
        .unwrap();
        let text = std::fs::read_to_string(dir.path().join(CARGO_CONFIG)).unwrap();
        assert!(text.contains("DOXA_DIST = \"/t/dist-android\""), "{text}");
        cargo_config(dir.path(), Target::Android, None).unwrap();
        assert!(!dir.path().join(CARGO_CONFIG).exists());
        std::fs::create_dir_all(dir.path().join(".cargo")).unwrap();
        std::fs::write(dir.path().join(CARGO_CONFIG), "[build]\n").unwrap();
        assert!(cargo_config(dir.path(), Target::Android, None).is_err());
    }
}
